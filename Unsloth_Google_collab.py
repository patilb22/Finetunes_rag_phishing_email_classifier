print("=" * 80)
print("             BASE MODEL vs. FINE-TUNED MODEL COMPARISON")
print("=" * 80 + "\n")

for sample in test_emails:
    # 1. Format input prompt without the answer
    formatted_prompt = phishing_prompt.format(sample["content"], "")
    inputs = tokenizer([formatted_prompt], return_tensors="pt").to("cuda")

    # 2. Generate prediction using BASE MODEL (Adapters Disabled)
    with model.disable_adapter():
        base_outputs = model.generate(
            **inputs,
            max_new_tokens=15,
            use_cache=True,
            temperature=0.1 # Low temperature for deterministic output
        )
        base_raw_response = tokenizer.batch_decode(base_outputs, skip_special_tokens=True)[0]
        base_pred = base_raw_response.split("### Classification:")[-1].strip()

    # 3. Generate prediction using FINE-TUNED MODEL (Adapters Enabled)
    ft_outputs = model.generate(
        **inputs,
        max_new_tokens=15,
        use_cache=True,
        temperature=0.1
    )
    ft_raw_response = tokenizer.batch_decode(ft_outputs, skip_special_tokens=True)[0]
    ft_pred = ft_raw_response.split("### Classification:")[-1].strip()

    # 4. Display comparative outputs
    print(f"📌 {sample['id']}")
    print(f"📧 EMAIL CONTENT: {sample['content'][:100]}...")
    print(f"🔴 BASE MODEL OUTPUT      : {base_pred}")
    print(f"🟢 FINE-TUNED MODEL OUTPUT : {ft_pred}")
    print("-" * 80 + "\n")
