# ==============================================================================
# STEP 2: Import Libraries & Configure Model Parameters
# ==============================================================================
import torch
from datasets import load_dataset
from transformers import TrainingArguments
from trl import SFTTrainer, SFTConfig
from unsloth import FastLanguageModel, is_bfloat16_supported

# Model configuration
max_seq_length = 2048  # Supports auto RoPE scaling for longer context
load_in_4bit = True   # Enable 4-bit QLoRA to fit comfortably in T4 VRAM (16GB)

# Load Llama 3.1 8B Instruct (or unsloth/llama-3-8b-Instruct-bnb-4bit for Llama 3)
model, tokenizer = FastLanguageModel.from_pretrained(
    model_name="unsloth/Meta-Llama-3.1-8B-Instruct-bnb-4bit",
    max_seq_length=max_seq_length,
    dtype=None,  # Auto-detects float16 for T4 or bfloat16 for Ampere+ GPUs
    load_in_4bit=load_in_4bit,
)

# ==============================================================================
# STEP 3: Setup Parameter-Efficient Fine-Tuning (LoRA Adapters)
# ==============================================================================
model = FastLanguageModel.get_peft_model(
    model,
    r=16,                  # Rank: higher values allow learning more complex tasks
    target_modules=[       # Target all linear projection layers for maximum efficiency
        "q_proj", "k_proj", "v_proj", "o_proj",
        "gate_proj", "up_proj", "down_proj"
    ],
    lora_alpha=16,         # Scaling factor
    lora_dropout=0,        # Standard Unsloth optimization (dropout = 0)
    bias="none",
    use_gradient_checkpointing="unsloth",  # Unsloth's custom memory-saving checkpointing
    random_state=3407,
)

# ==============================================================================
# STEP 4: Load Dataset, Split (80/20), and Apply Formatting
# ==============================================================================

# 1. Define prompt template
phishing_prompt = """Below is an email message. Analyze the text and classify it as either "Phishing" or "Safe".

### Email Content:
{}

### Classification:
{}"""

def format_phishing_prompts(examples):
    texts = []
    for email_text, label in zip(examples["Email Text"], examples["Email Type"]):
        # Format prompt with target response + end-of-sequence token
        text = phishing_prompt.format(email_text, label) + tokenizer.eos_token
        texts.append(text)
    return { "text": texts }

# 2. Load the full raw dataset
raw_dataset = load_dataset("zefang-liu/phishing-email-dataset", split="train")

# 3. Perform an 80/20 train/test split
dataset_split = raw_dataset.train_test_split(test_size=0.2, seed=3407)

# 4. Map the formatting function over both train and eval splits
train_dataset = dataset_split["train"].map(format_phishing_prompts, batched=True)
eval_dataset = dataset_split["test"].map(format_phishing_prompts, batched=True)

# ==============================================================================
# STEP 5: Initialize Trainer & Execute Fine-Tuning
# ==============================================================================

# ==============================================================================
# STEP 5: Initialize Trainer & Execute Fine-Tuning
# ==============================================================================


#from trl import SFTTrainer, SFTConfig

# 1. Define SFTConfig (replaces TrainingArguments and accepts dataset parameters)
sft_config = SFTConfig(
    # Training & Evaluation Args
    output_dir="outputs",
    per_device_train_batch_size=2,
    per_device_eval_batch_size=2,
    gradient_accumulation_steps=4,
    warmup_steps=5,
    max_steps=60,                   # Increase (e.g., 200+) for full fine-tuning
    learning_rate=2e-4,
    fp16=not is_bfloat16_supported(),
    bf16=is_bfloat16_supported(),
    logging_steps=10,
    eval_strategy="steps",          # Run periodic evaluation
    eval_steps=20,
    optim="adamw_8bit",
    weight_decay=0.01,
    lr_scheduler_type="linear",
    seed=3407,

    # Dataset-Specific Arguments moved into SFTConfig
    dataset_text_field="text",
    max_seq_length=max_seq_length,
    dataset_num_proc=2,
    packing=False,
)

# 2. Instantiate SFTTrainer using processing_class and sft_config
trainer = SFTTrainer(
    model=model,
    processing_class=tokenizer,
    train_dataset=train_dataset,
    eval_dataset=eval_dataset,
    args=sft_config,
)

# 3. Run fine-tuning loop
trainer.train()

# ==============================================================================
# STEP 5.5: Explicit Model Evaluation on 20% Held-out Split
# ==============================================================================

# 1. Evaluate cross-entropy validation loss via trainer
eval_results = trainer.evaluate()
print(f"\n--- Validation Loss: {eval_results['eval_loss']:.4f} ---")

# 2. Accuracy check on a sample subset of the 20% validation split
import numpy as np

FastLanguageModel.for_inference(model)

sample_eval = dataset_split["test"].shuffle(seed=3407).select(range(100)) # Sample 100 test examples
correct = 0

for item in sample_eval:
    prompt = phishing_prompt.format(item["Email Text"], "")
    inputs = tokenizer([prompt], return_tensors="pt").to("cuda")

    outputs = model.generate(**inputs, max_new_tokens=10, use_cache=True)
    generated_text = tokenizer.batch_decode(outputs, skip_special_tokens=True)[0]

    # Extract prediction after "### Classification:"
    prediction = generated_text.split("### Classification:")[-1].strip()
    ground_truth = str(item["Email Type"]).strip()

    if ground_truth.lower() in prediction.lower():
        correct += 1

accuracy = (correct / len(sample_eval)) * 100
print(f"--- Sample Accuracy on Test Split: {accuracy:.2f}% ---")

